    title: 'Leh Ladakh 4x4 Expedition',
    duration: '9 Days 8 Nights',
    route: 'Khardung La, Pangong Tso & Nubra Valley',
    image: 'https://images.unsplash.com/photo-1581793745862-99fde7fa73d2?auto=format&fit=crop&w=800&q=80'
