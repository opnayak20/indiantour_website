  const popupLeads = enquiries.filter(
    (enq) =>
      enq.notes?.includes('Popup') ||
      enq.message?.includes('[Trip Lead Popup') ||
      enq.source === 'popup_lead'
  );
  const displayLeads = popupLeads.length > 0 ? popupLeads : enquiries.slice(0, 10);

